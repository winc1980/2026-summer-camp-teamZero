/*
 * textが指すUTF-8先頭1文字をUnicode番号へ変換し、*textを次の文字へ進める。
 * const char **は「文字列ポインタそのものを書き換える」二重ポインタ（4章発展）。
 * このゲームで必要な1〜3バイトUTF-8だけを対象とし、4バイト文字は未対応。
 */
static uint16_t decodeUtf8(const char **text)
{
    /* charの符号有無に左右されずビット判定するためunsigned char *へキャストする。 */
    const unsigned char *bytes = (const unsigned char *)*text;
    uint16_t codepoint;

    /* 先頭bitが0のASCIIは1バイト。その値がそのままUnicode番号。 */
    if (bytes[0] < 0x80) {
        /* (*text)++ はtextが指している文字列ポインタを1バイト進める。 */
        (*text)++;
        return bytes[0];
    }
    /* 110xxxxx 10xxxxxx の2バイト文字。マスク後に6bitずらして結合する。 */
    if ((bytes[0] & 0xE0) == 0xC0 && bytes[1] != 0) {
        /* | はビットOR。分割されていたUnicodeのbit列を1つへつなぐ（8章）。 */
        codepoint = (uint16_t)(((bytes[0] & 0x1F) << 6) | (bytes[1] & 0x3F));
        *text += 2;
        return codepoint;
    }
    /* 1110xxxx 10xxxxxx 10xxxxxx の3バイト文字。日本語の多くがここを通る。 */
    if ((bytes[0] & 0xF0) == 0xE0 && bytes[1] != 0 && bytes[2] != 0) {
        codepoint = (uint16_t)(((bytes[0] & 0x0F) << 12) |
                               ((bytes[1] & 0x3F) << 6) |
                               (bytes[2] & 0x3F));
        *text += 3;
        return codepoint;
    }
    /* 壊れた並びや4バイト文字は1バイトだけ進め、代替文字?を返す。 */
    (*text)++;
    return '?';
}

/* Unicode番号に対応するグリフを線形探索する。 */
static const JapaneseGlyph *findGlyph(uint16_t codepoint)
{
    size_t i;
    /* sizeof(配列)/sizeof(1要素)で、ハードコードせず要素数を求める（5章）。 */
    for (i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++) {
        if (glyphs[i].codepoint == codepoint) return &glyphs[i];
    }
    /* 未収録文字は?のグリフを再検索して表示する。?自体は表に必ず存在する。 */
    return findGlyph('?');
}

/* UTF-8文字列全体を、指定したVRAM座標へ左から順に描画する。 */
void japaneseTextDraw(u16 *pixels, int x, int y, const char *text, u16 color)
{
    /* 改行時に戻る左端を保存する。 */
    int originX = x;

    /* C文字列の終端'\0'に到達するまで繰り返す（5章）。 */
    while (*text != '\0') {
        uint16_t codepoint;
        const JapaneseGlyph *glyph;
        int width;
        int row;
        int column;

        /* 改行文字はグリフを描かず、xを左端、yを8px下へ移す。 */
        if (*text == '\n') {
            text++;
            x = originX;
            y += 8;
            continue;
        }
        /* decodeUtf8がtextを次文字へ進め、findGlyphがドット表を返す。 */
        codepoint = decodeUtf8(&text);
        glyph = findGlyph(codepoint);
        /* 美咲フォントの英数字は4px幅、日本語は8px幅として詰めて表示する。 */
        width = codepoint < 0x80 ? 4 : 8;
        /* 8行×文字幅の各bitを調べ、1の画素だけ前景色で書く。背景はclearUi済み。 */
        for (row = 0; row < 8; row++) {
            for (column = 0; column < width; column++) {
                /*
                 * 0x80 >> columnで左から1bitずつ調べる。
                 * 後半の条件はVRAM配列の外へ書かないための境界チェック。
                 */
                if ((glyph->rows[row] & (0x80 >> column)) != 0 &&
                    x + column >= 0 && x + column < 256 && y + row >= 0 && y + row < 192) {
                    /* 2次元画面座標を1次元配列番号へ変換して色を代入する。 */
                    pixels[(y + row) * 256 + x + column] = color;
                }
            }
        }
        /* 次の文字を、今回描いた幅の右隣から開始する。 */
        x += width;
    }
}
